    // Offline German -> English vocabulary (from Diogenes-ImGui, written for Mercedes data). BMW coding
    // abbreviations are added in BmwGlossary.cs.
    // Keys are lowercase with umlauts transliterated (ae, oe, ue, ss) - see GermanText.Normalize.
    // Line format:  german=english[|flags]
    //   v : verb (moved to the front of a phrase, "Fehlerspeicher lesen" -> "Read fault memory")
    //   s : standalone only (function words that must never be matched inside a compound word)
    // An empty english value drops the word (articles).
    public static partial class GermanGlossary
    {
        public class Entry
        {
            public string English;
            public bool IsVerb;
            public bool StandaloneOnly;
        }

        public static readonly Dictionary<string, Entry> Words = new Dictionary<string, Entry>();

        // phrases are matched before single words, on normalized text with single spaces
        public static readonly List<KeyValuePair<string, string>> Phrases = new List<KeyValuePair<string, string>>();

        static GermanGlossary()
        {
            foreach (string rawLine in (WordList + BmwWordList).Split('\n'))
            {
                string line = rawLine.Trim();
                if (line.Length == 0 || line.StartsWith("#"))
                {
                    continue;
                }
                int eq = line.IndexOf('=');
                if (eq <= 0)
                {
                    continue;
                }
                string key = line.Substring(0, eq).Trim();
                string value = line.Substring(eq + 1);
                string flags = "";
                int bar = value.IndexOf('|');
                if (bar >= 0)
                {
                    flags = value.Substring(bar + 1);
                    value = value.Substring(0, bar);
                }
                Words[key] = new Entry
                {
                    English = value.Trim(),
                    IsVerb = flags.Contains('v'),
                    StandaloneOnly = flags.Contains('s') || key.Length < 3,
                };
            }

            foreach (string rawLine in PhraseList.Split('\n'))
            {
                string line = rawLine.Trim();
                int eq = line.IndexOf('=');
                if (eq <= 0)
                {
                    continue;
                }
                Phrases.Add(new KeyValuePair<string, string>(line.Substring(0, eq).Trim(), line.Substring(eq + 1).Trim()));
            }
            // longest phrases first so "kurzschluss nach masse" wins over "nach masse"
            Phrases.Sort((a, b) => b.Key.Length.CompareTo(a.Key.Length));
        }

